                "页脚版权" to "© 2026 百分点科技集团股份有限公司 版权所有",
            ),
        ),
    )

    @Test
    fun `把每套骨架装配成成品页落盘，供人肉眼验收`() {
        val assets = assetsDir()
        val out = outDir()
        val written = ArrayList<String>()

        for (template in WebTemplates.all) {
            val sample = samples[template.id]
            assertTrue("示例内容里漏了「" + template.id + "」，预览会缺一套", sample != null)
            val (theme, points, extras) = sample!!

            val html = File(assets, template.assetPath).readText(Charsets.UTF_8)
            // 用户已经说清楚的那些槽位，装配完**一个都不许再留着花括号**。
            // 这条断言盯的就是「页面上露出 {{要点1说明}}」那种一眼假的结果：
            // 只要调用方给了内容，就轮不到模型去补。
            //
            // 「给了」要按装配规则算，不能凭想象加：副标题只有真的传了才该被替换，
            // 要点只填前 N 条（骨架就那么几张卡片）。断言比实现更严格的话，
            // 报出来的就是假警报，久了就没人看它了。
            val supplied = ArrayList<String>()
            supplied.add(template.primarySlot)
            supplied.add(template.titleSlot)
            if (extras["副标题"].orEmpty().isNotBlank()) supplied.add(template.subSlot)
            supplied.addAll(template.bulletSlots.take(WebTemplates.bulletPoints(points).size))
            supplied.addAll(extras.keys)

            for (colors in ColorSchemes.all) {
                val filled = WebTemplates.fill(template, html, theme, points, extras, colors)
                assertTrue(
                    template.id + " × " + colors.id + "：还有没替换掉的 {{配色变量}}",
                    !filled.contains("{{配色变量}}"),
                )
                for (slot in supplied) {
                    assertFalse(
                        template.id + " × " + colors.id + "：用户给了「" + slot +
                            "」的内容，成品里却还露着 {{" + slot + "}}",
                        filled.contains("{{" + slot + "}}"),
                    )
                }
                val name = WebTemplates.fileNameStem(template) + "-" + colors.id + ".html"
                File(out, name).writeText(filled, Charsets.UTF_8)
                written.add(name)
            }
        }
        assertTrue("应该产出模板 × 配色的全部组合", written.size == WebTemplates.all.size * ColorSchemes.all.size)
    }

    /**
     * 复刻真机上那一单：只给了主题和要点，**没给**统计数字和联系方式。
     *
     * 真机结果是在页面上留下 `{{数据1}}`、`{{联系电话}}`。这一版应当把统计条和联系
     * 方式列整块去掉，页面上不出现任何花括号。产物落在同一个目录，便于对照着看。
     */
    @Test
    fun `只给主题和要点时，与主题无关的区块整块消失`() {
        val assets = assetsDir()
        val out = outDir()
        for (template in WebTemplates.all) {
            val html = File(assets, template.assetPath).readText(Charsets.UTF_8)
            val filled = WebTemplates.fill(
                template,
                html,
                "数字媒体",
                "专业介绍、实验室开放",
                emptyMap(),
                ColorSchemes.byId("墨黑金")!!,
            )
            assertFalse(
                template.id + "：还留着花括号，真机上的症状会重演",
                filled.contains("{{数据") || filled.contains("{{联系电话}}") ||
                    filled.contains("{{邮箱}}") || filled.contains("{{地址}}"),
            )
            assertFalse(template.id + "：区块标记不能留在成品里", filled.contains("<!--可选-->"))
            assertTrue(template.id + "：主题必须进大标题", filled.contains(">数字媒体<"))
            File(out, WebTemplates.fileNameStem(template) + "-只有主题.html")
                .writeText(filled, Charsets.UTF_8)
        }
    }
